/* Q1.  DDL (Data Definition Language) defines/changes database structures rather than data; example commands: CREATE TABLE, ALTER TABLE, DROP TABLE. */
/* Q2.  It registers a new relation in the system catalogs (pg_class/pg_attribute), allocates its storage file on disk, and sets up any constraints/indexes/sequences the definition implies. */
/* Q3.  Declared types let the engine validate every write, store data compactly, and use type-aware indexing/sorting/arithmetic - without types the database couldn't catch bad data or optimize storage and queries. */
/* Q4.  VARCHAR(50) caps length at 50 chars and documents an intended limit; TEXT is unlimited length - pick VARCHAR(n) when a real business limit exists (e.g. a code), TEXT when length is genuinely open-ended (a review). */
/* Q5.  NUMERIC does exact, base-10 arithmetic with no rounding error, while FLOAT is binary floating-point and can silently misrepresent decimal fractions like 0.1 - unacceptable for money. */
/* Q6.  SERIAL gives you an auto-incrementing INT column backed by a sequence, a DEFAULT nextval(...) on that sequence, and an implicit NOT NULL - all set up automatically. */
/* Q7.  Use BIGSERIAL when the row count could exceed ~2.1 billion (INT's max) over the table's lifetime, e.g. a high-volume events/log table. */
/* Q8.  TIMESTAMP stores both date and time-of-day; DATE stores only the calendar date with no time component. */
/* Q9.  Use TIMESTAMPTZ whenever the data crosses time zones (multi-region users, servers) - it stores/normalizes to UTC internally and converts on display, avoiding ambiguity that plain TIMESTAMP can't resolve. */
/* Q10. JSONB stores JSON in a parsed, indexable binary format that supports operators (->, @>) and GIN indexing; TEXT containing JSON is just an opaque string the database can't query or validate as JSON. */
/* Q11. UUID is a 128-bit globally unique identifier; use it instead of SERIAL when IDs must be generated by multiple systems/clients without coordination (e.g. offline mobile inserts, merging data from many sources). */
/* Q12. CREATE DATABASE makes a whole new, isolated database (separate connection target); CREATE SCHEMA makes a named namespace of tables inside the CURRENT database. */
/* Q13. Yes - as long as they're in different schemas (or different databases); schema-qualified names (sales.orders vs archive.orders) disambiguate identically-named tables. */
/* Q14. Unquoted identifiers are folded to lowercase automatically, so "Customers" becomes customers anyway; writing it lowercase from the start avoids confusion about whether quoting will be needed later. */
/* Q15. IF NOT EXISTS makes CREATE TABLE a no-op (instead of erroring) when the table already exists - useful for idempotent setup scripts you might re-run safely. */
/* Q16. CASCADE also drops every object that depends on the table (views, foreign keys referencing it, etc.); plain DROP TABLE fails if any such dependent object still exists. */
/* Q17. DROP DATABASE permanently deletes the entire database and all its data with no undo, and it disconnects/blocks if anyone is still connected - one mistaken command on the wrong DB name destroys everything. */
/* Q18. The new column is filled with NULL (or its DEFAULT, if one is specified) for every existing row. */
/* Q19. No - DROP COLUMN permanently discards that column's data outside of a transaction; the only way back is restoring from a backup, or being inside a still-open transaction you can ROLLBACK. */
/* Q20. Postgres rewrites the table converting every existing value to the new type (using an implicit or explicit USING cast) - if any value can't be cast, the whole ALTER fails and nothing changes. */
/* Q21. CHAR(10) is fixed-length and pads shorter values with trailing spaces to exactly 10 characters; VARCHAR(10) is variable-length up to 10 characters with no padding. */
/* Q22. Use BOOLEAN - it's self-documenting (true/false), and Postgres stores it in a single byte just like a 0/1 INT would, with none of the ambiguity of what other integer values might mean. */
/* Q23. Adding a column with a volatile DEFAULT (pre-PG11) required rewriting every existing row, taking a long exclusive lock; even now, careless ALTERs on huge tables can still trigger a full table rewrite for certain type/constraint changes. */
/* Q24. Domain integrity means every value in a column must belong to that column's valid set of values (its type/range/format); declaring the right data type is the first, automatic line of enforcement for that rule. */
/* Q25. Phone numbers aren't used for arithmetic, can have leading zeros or a '+' country code that INT would silently strip/misparse, and can exceed INT's numeric range in some formats - VARCHAR preserves them exactly as written. */

