/* Q76. VARCHAR(15) - phone numbers can include a leading '+' and country code and are never used arithmetically, so a short variable-length string is correct: phone VARCHAR(15). */
/* Q77. NUMERIC(12,2) - exact decimal money with paisa precision and no floating-point rounding error: lifetime_spend NUMERIC(12,2). */
/* Q78. TEXT - a few sentences has no fixed cap worth enforcing, so use an unbounded description TEXT. */
/* Q79. BOOLEAN - a clean true/false opt-in flag: marketing_opt_in BOOLEAN. */
/* Q80. TIMESTAMPTZ - needs both millisecond precision and timezone awareness: clicked_at TIMESTAMPTZ(3). */
/* Q81. DATE - only the calendar date matters, no time-of-day: joined_on DATE. */
/* Q82. VARCHAR(50) - a UPI VPA is short text like a username@bank string, comfortably under 50 chars: vpa VARCHAR(50). */
/* Q83. VARCHAR(6) with a CHECK constraint - store as text (leading zeros matter) with CHECK (pincode ~ '^[0-9]{6}$'): pincode VARCHAR(6) CHECK (pincode ~ '^[0-9]{6}$'). */
/* Q84. NUMERIC(9,6) - latitude needs a handful of decimal places of precision without floating-point drift: latitude NUMERIC(9,6). */
/* Q85. SERIAL (INT) - a ~50-row lookup table will never approach INT's range, so the smaller/simpler default is right: id SERIAL PRIMARY KEY. */
/* Q86. BIGSERIAL (BIGINT) - 1B+ rows will overflow a 32-bit INT's ~2.1B ceiling well within the table's lifetime: id BIGSERIAL PRIMARY KEY. */
/* Q87. JSONB - nested nested JSON from a webhook benefits from JSONB's indexable, queryable binary storage: payload JSONB. */
/* Q88. UUID - globally unique, hard-to-guess, generable client-side without a DB round trip: session_token UUID DEFAULT gen_random_uuid(). */
/* Q89. SMALLINT - a 1-1000 range comfortably fits SMALLINT's -32768..32767 range and saves space over INT: quantity SMALLINT. */
/* Q90. NUMERIC(5,2) - exact 2-decimal percentage with no float rounding error: discount_pct NUMERIC(5,2). */
/* Q91. TEXT - 5,000 characters exceeds a typical VARCHAR(n) business limit and has no natural cap, so use unbounded TEXT: review_text TEXT. */
/* Q92. BOOLEAN - a clean yes/no flag: is_email_verified BOOLEAN. */
/* Q93. DATE - a range start with no time component: valid_from DATE. */
/* Q94. TEXT (or VARCHAR(2048)) - URLs can exceed typical VARCHAR limits and have no fixed length; TEXT is simplest: url TEXT. */
/* Q95. NUMERIC(7,4) - needs exact 4-decimal precision for a tax rate like 18.0000: tax_rate NUMERIC(7,4). */
/* Q96. TEXT[] for a small fixed set of simple tags, OR a normalized post_tags(post_id, tag) junction table if tags need their own metadata/uniqueness/reporting - the junction table is the more scalable, query-friendly design. */
/* Q97. INET - Postgres's native INET type stores both IPv4 and IPv6 addresses compactly and supports network-aware operators: ip_address INET. */
/* Q98. CHAR(64) - a SHA-256 hex digest is always exactly 64 hex characters, so the fixed-length CHAR(64) is a precise fit: content_hash CHAR(64). */
/* Q99. NUMERIC(12,4) - needs 4-decimal precision for currency-conversion-grade USD prices: price_usd NUMERIC(12,4). */
/* Q100. CHAR(1) - a single fixed-width status code letter is exactly what CHAR(1) models: status CHAR(1). */

