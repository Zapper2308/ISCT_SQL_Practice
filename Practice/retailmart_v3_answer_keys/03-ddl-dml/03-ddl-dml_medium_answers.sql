/* Q1.  NUMERIC(10,2) is exact with a fixed 2-decimal scale (money); plain NUMERIC is exact but unbounded precision/scale (rarely needed, slightly slower); FLOAT is inexact binary floating point - pick NUMERIC(p,s) for money, plain NUMERIC only for arbitrary-precision math, FLOAT only for scientific data where tiny rounding error is acceptable. */
/* Q2.  A 4-byte INT sequence tops out around 2.1 billion values, which is plenty for most entity tables (customers, products), but a high-volume events table can realistically generate that many rows within months - so it needs BIGSERIAL/BIGINT from day one. */
/* Q3.  A GENERATED ALWAYS AS column is computed automatically from other columns in the same row and stored on write; a RetailMart-like use case is order_items.net_amount GENERATED ALWAYS AS (gross_amount - discount_amount) STORED. */
/* Q4.  CHAR(64) pads/wastes nothing extra for a fixed 64-char hash but forces exactly 64 (wasteful if you ever store a shorter hash); VARCHAR(64) is equally fast in Postgres and self-documents the max length - VARCHAR(64) is generally best since Postgres treats CHAR and VARCHAR storage almost identically internally. */
/* Q5.  TIMESTAMPTZ matters more whenever users/servers span time zones - e.g. logging when a Mumbai customer clicked "buy" vs a US-based analyst querying it, TIMESTAMPTZ normalizes to UTC so comparisons and ordering stay correct regardless of each viewer's local zone. */
/* Q6.  INTERVAL stores a span of time (days/months/seconds) as its own type supporting date arithmetic; it's needed whenever you compute or store a duration, e.g. "shipments.delivered_date - shipments.shipped_date" or a subscription's billing_cycle INTERVAL '1 month'. */
/* Q7.  TEXT[] is simple and fast for a small, unstructured set of tags with no per-tag metadata (a blog post's tags); a child table wins once tags need their own attributes, need to be queried/joined efficiently at scale, or need referential integrity (a controlled vocabulary of tags). */
/* Q8.  Use ENUM for a small, truly fixed set of values baked into the domain model (order_status); the migration tax is that ALTER TYPE ... ADD VALUE cannot run inside a transaction with other DDL/DML, and removing/reordering values is awkward - a lookup table is more flexible for values that might grow or need extra attributes. */
/* Q9.  UUID wins for a "tracking event" PK because events are often generated by multiple independent clients/services that need to mint a globally-unique ID without a round trip to a central sequence; SERIAL requires one authoritative counter, which becomes a bottleneck/single point of coordination at that scale. */
/* Q10. SMALLINT is 2 bytes (-32,768 to 32,767), INT is 4 bytes (~-2.1B to 2.1B), BIGINT is 8 bytes (~-9.2 quintillion to 9.2 quintillion) - each doubling in size trades disk/index space for a larger safe range. */
/* Q11. FLOAT/REAL use inexact binary floating-point representation, so values like 0.1 or 19.99 can't be stored exactly - any financial or exact-comparison logic built on them eventually produces silently wrong totals or failed equality checks. */
/* Q12. NUMERIC(20,4) stores latitude with exact, predictable decimal precision (no drift across repeated calculations); DOUBLE PRECISION is faster and adequate for most GPS use cases too, but loses NUMERIC's guarantee of exact decimal representation - NUMERIC is safer when latitude feeds into exact comparisons or financial-grade audits. */
/* Q13. They're functionally identical in PostgreSQL - NOW() is Postgres's own function, CURRENT_TIMESTAMP is the SQL-standard syntax; both return the current transaction's start timestamp with time zone. */
/* Q14. PostgreSQL doesn't implement MySQL's "ON UPDATE CURRENT_TIMESTAMP" column option; PG users instead write a small BEFORE UPDATE trigger that sets NEW.updated_at = now() on every row update. */
/* Q15. BOOLEAN is self-documenting (true/false/unknown via NULL), takes the same 1 byte as CHAR(1), and every ORM/driver maps it natively - CHAR(1) with 'Y'/'N' just adds ambiguity (what does 'X' mean?) with zero storage or performance benefit. */
/* Q16. BYTEA stores raw binary data (images, files, encrypted blobs) directly in a row; you'd usually NOT store large binaries in the database - keep them in object storage (S3-like) and store only the URL/path, since BYTEA bloats table size, backups, and replication. */
/* Q17. TIMESTAMP(3) means the same TIMESTAMP type but with fractional-second precision truncated/rounded to 3 digits (milliseconds); plain TIMESTAMP defaults to full microsecond (6-digit) precision. */
/* Q18. JSONB is overkill when the fields are well-known, always present, and queried/filtered often (those belong in real typed columns with indexes); it's the right call when the shape is genuinely sparse, variable per row, or evolving faster than migrations can keep up (webhook payloads, feature-flag configs). */
/* Q19. INET understands IP address semantics (validates format, supports subnet/containment operators like <<, sorts numerically) - a VARCHAR just stores text with no validation and no IP-aware comparison, letting garbage or unsortable values slip in. */
/* Q20. Modern PostgreSQL (10+) prefers GENERATED ALWAYS AS IDENTITY because it's SQL-standard, doesn't expose a separately-manipulable sequence object the way SERIAL's implicit sequence does, and integrates more cleanly with role/privilege management. */
/* Q21. Even with cheap disk, a wider integer type means wider indexes (more pages to scan/cache), more RAM used by shared_buffers to hold the same working set, and slower comparisons at high row counts - so the smallest correct type still measurably helps performance. */
/* Q22. CITEXT enforces case-insensitive comparison and uniqueness AT THE TYPE/INDEX level once, so every query, constraint, and index automatically behaves case-insensitively; scattering LOWER() calls everywhere is easy to forget in just one query or constraint, silently breaking case-insensitive matching or letting duplicate-but-differently-cased rows slip past a UNIQUE constraint. */
/* Q23. A stored/calculated field is fast to read (no recomputation) but must be kept in sync on every write (risk of drift, more write cost); computing on-the-fly is always correct and needs no upkeep, but costs CPU on every read - store it when reads vastly outnumber writes and staleness is unacceptable. */
/* Q24. id (PK), created_at, updated_at, a soft-delete marker (deleted_at or is_active), and some form of created_by/owner reference are the five columns almost every business table benefits from having. */
/* Q25. Schema-per-tenant gives strong data isolation and easy per-tenant backup/restore but doesn't scale past a few hundred tenants (too many schemas/connections to manage); row-per-tenant (a shared table + tenant_id column) scales to millions of tenants but needs careful discipline (RLS, always filtering by tenant_id) to avoid cross-tenant leaks - pick schema-per-tenant for a handful of large enterprise customers, row-per-tenant for many small ones. */

