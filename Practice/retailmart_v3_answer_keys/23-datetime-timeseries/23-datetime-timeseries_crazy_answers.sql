SELECT cohort_month, months_since, cohort_size, retained, round(100.0 * retained / NULLIF(cohort_size, 0), 2) AS retention_pct
FROM (
  SELECT cm.cohort_month, p.months_since,
         count(DISTINCT o.cust_id) FILTER (WHERE date_trunc('month', o.order_date) = cm.cohort_month + (p.months_since || ' months')::interval) AS retained,
         count(DISTINCT c.customer_id) AS cohort_size
  FROM (SELECT DISTINCT date_trunc('month', registration_date)::date AS cohort_month FROM customers.customers) cm
  CROSS JOIN generate_series(0, 11) AS p(months_since)
  JOIN customers.customers c ON date_trunc('month', c.registration_date)::date = cm.cohort_month
  LEFT JOIN sales.orders o ON o.cust_id = c.customer_id
  GROUP BY cm.cohort_month, p.months_since
) x
ORDER BY cohort_month, months_since;

