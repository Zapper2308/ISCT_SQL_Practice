SELECT month,
       sum(net_total) FILTER (WHERE segment = 'new') AS new_revenue,
       sum(net_total) FILTER (WHERE segment = 'reactivated') AS reactivated_revenue,
       sum(net_total) FILTER (WHERE segment = 'returning') AS returning_revenue
FROM (
  SELECT o.order_id, o.net_total, date_trunc('month', o.order_date)::date AS month,
         CASE WHEN o.order_date = f.first_order_date THEN 'new'
              WHEN o.order_date - lag(o.order_date) OVER (PARTITION BY o.cust_id ORDER BY o.order_date) > 90 THEN 'reactivated'
              ELSE 'returning' END AS segment
  FROM sales.orders o
  JOIN (SELECT cust_id, min(order_date) AS first_order_date FROM sales.orders GROUP BY cust_id) f ON f.cust_id = o.cust_id
) x
GROUP BY month
ORDER BY month;

