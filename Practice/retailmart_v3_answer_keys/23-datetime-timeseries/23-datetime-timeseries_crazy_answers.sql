WITH daily AS (
  SELECT r.region_name, d.day::date, coalesce(sum(o.net_total), 0) AS revenue
  FROM core.dim_region r
  CROSS JOIN generate_series('2025-06-01'::date, '2025-08-31'::date, interval '1 day') AS d(day)
  LEFT JOIN stores.stores s ON s.region_id = r.region_id
  LEFT JOIN sales.orders o ON o.store_id = s.store_id AND o.order_date = d.day
  GROUP BY r.region_name, d.day
),
thresh AS (
  SELECT region_name,
         percentile_cont(0.95) WITHIN GROUP (ORDER BY revenue) AS p95,
         percentile_cont(0.99) WITHIN GROUP (ORDER BY revenue) AS p99
  FROM daily
  GROUP BY region_name
),
flagged AS (
  SELECT d.region_name, d.day, d.revenue, t.p95, t.p99, d.revenue > t.p95 AS beyond_p95
  FROM daily d JOIN thresh t ON t.region_name = d.region_name
),
streaks AS (
  SELECT region_name, day, beyond_p95,
         day - (row_number() OVER (PARTITION BY region_name, beyond_p95 ORDER BY day))::int AS grp
  FROM flagged
  WHERE beyond_p95
)
SELECT region_name, min(day) AS streak_start, max(day) AS streak_end, count(*) AS streak_len
FROM streaks
GROUP BY region_name, grp
ORDER BY streak_len DESC
LIMIT 20;

