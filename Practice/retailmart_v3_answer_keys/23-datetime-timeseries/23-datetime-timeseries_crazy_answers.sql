/* Q1. Layer a persistent date-dimension table (date_key PK, calendar+fiscal+ISO+flag columns) below fact tables keyed by the same date_key, indexed on date_key and any commonly-filtered flag, so every fact joins to one shared, pre-computed calendar. */
/* Q2. A calendar dimension is precomputed once and indexed, so repeated dashboard queries just SELECT/JOIN against it (cheap); generate_series recomputes the spine on every query execution (flexible, zero storage, but pays CPU each time) - the dimension wins at high query volume, generate_series wins for ad-hoc/rare queries. */
/* Q3. Recompute a date range (e.g. "yesterday" or "last 7 days") and write it with a DELETE-then-INSERT (or UPSERT) targeting only that range, so re-running the same backfill for the same dates always yields identical results rather than double-counting. */
/* Q4. For each spine row, find the latest fact row with a timestamp <= that spine point (via LATERAL + ORDER BY ts DESC LIMIT 1, or DISTINCT ON) - this reconstructs "what was true as of this moment" even when facts don't align to the spine grid. */
/* Q5. Split events into sessions by ordering per entity, computing the gap to the previous event, and starting a new session whenever the gap exceeds a threshold; a cumulative SUM of "new session" flags assigns a session id in one windowed pass, avoiding row-by-row procedural loops. */
/* Q6. Row-number-difference: number rows per entity ordered by date, subtract as days, group by the result - fast, purely set-based. LAG-based: flag a new group whenever the gap to the previous row exceeds 1, then cumulative-sum the flags - both are O(n log n) but LAG is more flexible for non-integer/date gaps. */
/* Q7. LOCF: window function `coalesce(value, lag(value) IGNORE NULLS OVER (ORDER BY date))` (or a subquery picking the last non-null prior row) carries the most recent known value forward into every gap in a sparse series. */
/* Q8. Time-weighted average multiplies each observed value by the DURATION it was in effect (the width of its step in a step function), sums those products, and divides by total elapsed time - this correctly weights long-stable periods over instantaneous snapshots. */
/* Q9. Store every event in UTC; at report time convert with `ts AT TIME ZONE 'UTC' AT TIME ZONE region_tz` per viewer's region, keeping the underlying stored value canonical and letting presentation vary by audience. */
/* Q10. Epoch differences assume every day is exactly 86400 seconds; across a DST transition a local day can be 23 or 25 hours, so naive epoch math can misstate elapsed wall-clock time in DST zones - IST has no DST so this specific pitfall doesn't apply to India-only reporting. */
/* Q11. RANGE frames scan a logical window of rows matching an ORDER BY value range, which can require re-scanning duplicate/boundary rows; performance and memory depend on how many rows fall in the range, not a fixed count, so wide time ranges over dense data can be costly without care. */
/* Q12. ISO week 1 of a year contains that year's first Thursday, so late-December dates can fall in "week 1" of the following ISO year (and early-January dates in the last ISO week of the previous year) - always pair IW with IYYY, not the calendar year, to avoid a mismatched label. */
/* Q13. A 4-4-5 fiscal calendar groups 13 weeks per quarter as 4+4+5 weeks instead of calendar months; periods are generated by counting fixed week-blocks from a fiscal-year start date rather than by calendar month boundaries. */
/* Q14. A cohort/retention triangle stores cohort_period (anchor, e.g. registration month) x offset_period (months/weeks since anchor) x metric, shaped as a matrix where later cohorts naturally have fewer completed offset periods observed so far. */
/* Q15. Percentile bands (e.g. beyond P95/P99) are simple and robust to skewed, non-normal metrics like revenue; a moving z-score assumes roughly normal variation and is more sensitive to a shifting baseline/trend - percentile is usually safer for retail time-series with spikes. */
/* Q16. Choose day grain for granular anomaly detection, week for smoothing day-of-week seasonality, month for exec trend lines; pre-aggregation tiers (daily -> weekly -> monthly rollups) let each grain be served from a cheaper, smaller precomputed table instead of re-scanning raw facts. */
/* Q17. Backfill recomputes a historical range in bulk (good for corrections/reprocessing, can be resource-heavy); streaming append adds only new rows as they arrive (low latency, low cost per event) - production systems often need both: backfill for corrections, streaming for freshness. */
/* Q18. Late-arriving facts (e.g. a payment recorded a day after the order) require the daily mart to be idempotently re-runnable for the affected date - typically a small trailing window (e.g. last 3-7 days) is always recomputed on each run so late data gets folded in without reprocessing all history. */
/* Q19. Row normalization compares cells within their own weekday (or hour) context; column normalization compares within the same hour across weekdays; global normalization compares every cell to the overall max/total - each answers a different "relative to what?" question for the same heatmap. */
/* Q20. A materialized view is a stored, refreshable snapshot (fast reads, needs REFRESH); a summary table is similar but you control the write logic yourself (more flexible incremental updates); a live query is always current but recomputes every time - the right choice depends on staleness tolerance and query frequency. */
/* Q21. BRIN indexes are tiny and excellent for naturally-ordered, append-only timestamp columns spanning huge ranges (like an events log); btree indexes are better for selective point/range lookups or when data isn't well-correlated with insertion order - time-range dashboards on a huge append-only table often favor BRIN. */
/* Q22. date_trunc(ts) in a WHERE clause is an expression the planner can't match to a plain index on ts, forcing a sequential scan; creating an expression index (`CREATE INDEX ON tbl (date_trunc('day', ts))`) lets the planner use an index for that exact expression again. */
/* Q23. Parameterize spines as views/functions taking start/end or a "days back" argument (e.g. a set-returning function wrapping generate_series), so "last 30 days," "fiscal YTD," etc. become reusable building blocks instead of copy-pasted date literals in every query. */
/* Q24. Sum the daily rollup for a month and compare it to the monthly aggregate table's stored value for that month - any mismatch signals a late-arriving fact, a double-write, or a backfill gap that needs investigating before the rollups can be trusted. */
/* Q25. Define the metric's window (e.g. trailing 30 days), compute median/P95 per period, and count "breaches" (values exceeding an SLA threshold) per period to get a breach rate over time - this turns a raw SLA target into a trackable, alertable time series. */

