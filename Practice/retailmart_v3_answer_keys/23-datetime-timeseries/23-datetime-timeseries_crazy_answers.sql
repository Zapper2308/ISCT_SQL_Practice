SELECT r.region_name, month,
       sum(net_total) FILTER (WHERE segment = 'new') AS new_revenue,
       sum(net_total) FILTER (WHERE segment = 'reactivated') AS reactivated_revenue,
       sum(net_total) FILTER (WHERE segment = 'returning') AS returning_revenue,
       round(100.0 * sum(net_total) FILTER (WHERE segment = 'new') / NULLIF(sum(net_total), 0), 2) AS new_pct
FROM (
  SELECT o.order_id, o.net_total, s.region_id, date_trunc('month', o.order_date)::date AS month,
