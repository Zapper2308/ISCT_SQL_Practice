SELECT cust_id,
       percentile_cont(0.5) WITHIN GROUP (ORDER BY gap_days) AS median_gap_days,
       CASE WHEN percentile_cont(0.5) WITHIN GROUP (ORDER BY gap_days) <= 30 THEN 'Frequent'
