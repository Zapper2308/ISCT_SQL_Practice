         lag(view_timestamp) OVER (PARTITION BY customer_id ORDER BY view_timestamp) AS prev_ts
  FROM web_events.page_views
  WHERE customer_id IS NOT NULL
),
flagged AS (
  SELECT customer_id, view_timestamp,
         CASE WHEN prev_ts IS NULL OR view_timestamp - prev_ts > interval '30 min' THEN 1 ELSE 0 END AS new_session
  FROM ordered
),
sessioned AS (
  SELECT customer_id, view_timestamp, sum(new_session) OVER (PARTITION BY customer_id ORDER BY view_timestamp) AS session_num
  FROM flagged
),
session_stats AS (
  SELECT customer_id, session_num, count(*) AS pages,
         min(view_timestamp) AS session_start,
         max(view_timestamp) - min(view_timestamp) AS duration
  FROM sessioned
  GROUP BY customer_id, session_num
)
SELECT extract(hour FROM session_start)::int AS start_hour,
       count(*) AS sessions,
       percentile_cont(0.5) WITHIN GROUP (ORDER BY extract(epoch FROM duration)) AS median_duration_sec,
       round(100.0 * count(*) FILTER (WHERE pages = 1) / count(*), 2) AS dropoff_pct
FROM session_stats
GROUP BY start_hour
ORDER BY start_hour;

