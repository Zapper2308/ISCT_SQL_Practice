WITH order_days AS (
  SELECT DISTINCT cust_id, order_date FROM sales.orders
),
grp AS (
  SELECT cust_id, order_date,
         order_date - (row_number() OVER (PARTITION BY cust_id ORDER BY order_date))::int AS grp_key
  FROM order_days
),
streaks AS (
  SELECT cust_id, grp_key, min(order_date) AS streak_start, max(order_date) AS streak_end, count(*) AS streak_len
  FROM grp
  GROUP BY cust_id, grp_key
),
gaps AS (
  SELECT cust_id, order_date, order_date - lag(order_date) OVER (PARTITION BY cust_id ORDER BY order_date) AS gap_days
  FROM order_days
)
SELECT s.cust_id, max(s.streak_len) AS longest_streak,
       max(g.gap_days) FILTER (WHERE g.gap_days > 30) AS longest_dormancy_days
FROM streaks s
LEFT JOIN gaps g ON g.cust_id = s.cust_id
GROUP BY s.cust_id
ORDER BY longest_streak DESC
LIMIT 20;

