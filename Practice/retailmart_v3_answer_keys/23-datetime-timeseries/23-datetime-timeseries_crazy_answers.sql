WITH order_dates AS (
  SELECT cust_id, order_date, lag(order_date) OVER (PARTITION BY cust_id ORDER BY order_date) AS prev_date
  FROM sales.orders
),
dormancy AS (
  SELECT cust_id, date_trunc('month', order_date)::date AS month, order_date - prev_date AS dormant_days
  FROM order_dates
  WHERE order_date - prev_date > 90
),
active_per_month AS (
  SELECT date_trunc('month', order_date)::date AS month, count(DISTINCT cust_id) AS active_customers
  FROM sales.orders
  GROUP BY 1
)
SELECT d.month, count(*) AS reactivations,
       round(100.0 * count(*) / NULLIF(a.active_customers, 0), 2) AS winback_pct
FROM dormancy d
JOIN active_per_month a ON a.month = d.month
GROUP BY d.month, a.active_customers
ORDER BY d.month;

