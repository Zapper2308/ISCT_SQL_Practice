/* Q99. */
WITH spine AS (
  SELECT d.day::date FROM generate_series('2025-01-01'::date, '2025-12-31'::date, interval '1 day') AS d(day)
),
facts AS (
  SELECT s.day, coalesce(sum(o.net_total), 0) AS revenue
  FROM spine s
  LEFT JOIN sales.orders o ON o.order_date = s.day
  GROUP BY s.day
),
mas AS (
  SELECT day, revenue,
         avg(revenue) OVER (ORDER BY day ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS ma_7day
  FROM facts
),
growth AS (
  SELECT day, revenue, ma_7day,
         round(100.0 * (revenue - lag(revenue) OVER (ORDER BY day)) / NULLIF(lag(revenue) OVER (ORDER BY day), 0), 2) AS mom_pct,
         round(100.0 * (revenue - lag(revenue, 365) OVER (ORDER BY day)) / NULLIF(lag(revenue, 365) OVER (ORDER BY day), 0), 2) AS yoy_pct
  FROM mas
),
anomalies AS (
  SELECT g.*, revenue > p.p95_revenue AS is_anomaly
  FROM growth g
  CROSS JOIN (SELECT percentile_cont(0.95) WITHIN GROUP (ORDER BY revenue) AS p95_revenue FROM facts) p
)
SELECT day, revenue, ma_7day, mom_pct, yoy_pct, is_anomaly,
       rank() OVER (ORDER BY revenue DESC) AS revenue_rank
FROM anomalies
ORDER BY day;

