/* Q27. */
SELECT n.nspname AS schema, t.relname AS table_name, a.attname AS pk_column
FROM pg_constraint con
JOIN pg_class t ON t.oid = con.conrelid
JOIN pg_namespace n ON n.oid = t.relnamespace
JOIN unnest(con.conkey) AS k(attnum) ON true
JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = k.attnum
WHERE con.contype = 'p' AND n.nspname NOT IN ('pg_catalog','information_schema')
ORDER BY schema, table_name;

/* Q28. */
SELECT tc.table_schema AS fk_schema, tc.table_name AS fk_table, kcu.column_name AS fk_column,
       ccu.table_schema AS ref_schema, ccu.table_name AS ref_table, ccu.column_name AS ref_column
FROM information_schema.table_constraints tc
JOIN information_schema.key_column_usage kcu ON kcu.constraint_name = tc.constraint_name AND kcu.table_schema = tc.table_schema
JOIN information_schema.constraint_column_usage ccu ON ccu.constraint_name = tc.constraint_name AND ccu.table_schema = tc.table_schema
WHERE tc.constraint_type = 'FOREIGN KEY'
ORDER BY fk_schema, fk_table;

